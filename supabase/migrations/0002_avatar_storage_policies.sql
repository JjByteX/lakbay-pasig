-- Storage policies for the avatars bucket (profile pictures).
--
-- The bucket was created by hand in the dashboard and never had policies, so
-- uploads from src/lib/avatar-storage.ts (path {userId}/{uuid}-{filename}) were
-- refused by row level security. Reads are open (the bucket is public and the
-- picture URL is stored on profiles.profile_picture). A signed-in account can
-- add, replace and remove files only inside its own folder.

create policy "avatars_select_public"
  on storage.objects for select
  using (bucket_id = 'avatars');

create policy "avatars_insert_own"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "avatars_update_own"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "avatars_delete_own"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = auth.uid()::text
  );
